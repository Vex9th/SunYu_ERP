def action_label(action: str) -> str:
    if action in ACTION_LABELS:
        return ACTION_LABELS[action]
    from backend.app.features.permission_catalog import PERMISSION_BY_KEY

    item = PERMISSION_BY_KEY.get(action)
    return item.label if item else action


